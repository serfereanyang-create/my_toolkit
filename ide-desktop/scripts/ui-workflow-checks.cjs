const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async ({ window, evaluate, settle, output }) => {
  window.setContentSize(1280, 860);
  await evaluate('document.documentElement.style.setProperty("--fs-base", "14px")');
  await settle();
  const key = async (keyCode) => {
    window.webContents.sendInputEvent({ type: 'keyDown', keyCode });
    window.webContents.sendInputEvent({ type: 'keyUp', keyCode });
    await settle();
  };
  await evaluate('window.uiPreview.scenario("conversation"); window.uiPreview.clear();');
  await settle();
  assert.equal(await evaluate('document.querySelectorAll(".rail-primary-new").length'), 1, 'one new conversation action');
  await evaluate('document.querySelector("[data-session-id=other] .rail-convo").click()');
  await settle();
  assert.equal(await evaluate('document.querySelector("[data-session-id=other] .rail-convo").getAttribute("aria-current")'), 'page', 'session selection is exposed');
  await evaluate('document.querySelector("[data-session-id=current] .rail-convo-more").click()');
  await settle();
  const focus = () => evaluate('({tag: document.activeElement.tagName, className: document.activeElement.className, text: document.activeElement.textContent?.slice(0, 120)})');
  const initialFocus = await focus();
  assert.match(initialFocus.className, /ctx-row/, `menu receives focus: ${JSON.stringify(initialFocus)}`);
  await evaluate('(document.querySelector(".ctx-row") || document.body).dispatchEvent(new KeyboardEvent("keydown", { key: "ArrowDown", bubbles: true, cancelable: true }))');
  await settle();
  const focusAfterArrow = await focus();
  assert.match(focusAfterArrow.text, /重命名/, `arrow moves within menu: ${JSON.stringify(focusAfterArrow)}`);
  await evaluate('(document.querySelector(".ctx-row") || document.body).dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true, cancelable: true }))');
  await settle();
  assert.equal(await evaluate('!!document.querySelector(".ctx-menu")'), false, 'Escape closes session menu');
  assert.equal(await evaluate('document.activeElement.classList.contains("rail-convo-more")'), true, 'Escape returns focus to trigger');
  await evaluate('window.uiPreview.scenario("running")');
  await settle();
  assert.equal(await evaluate('document.querySelector("[data-session-id=current] .rail-convo-state").textContent'), '运行中', 'running status is readable');
  await evaluate('document.querySelector("[data-session-id=current] .rail-convo-more").click()');
  await settle();
  const stopsBeforeEscape = await evaluate('window.uiPreview.events().filter(event => event.type === "stop").length');
  await key('Escape');
  assert.equal(await evaluate('!!document.querySelector(".ctx-menu")'), false, 'Escape closes session menu');
  assert.equal(await evaluate('document.activeElement.classList.contains("rail-convo-more")'), true, 'Escape returns focus to trigger');
  assert.equal(await evaluate('window.uiPreview.events().filter(event => event.type === "stop").length'), stopsBeforeEscape, 'closing a menu does not cancel running work');
  await evaluate('document.querySelector("[data-session-id=current] .rail-convo-more").click()');
  await settle();
  await evaluate('document.body.dispatchEvent(new MouseEvent("mousedown", { bubbles: true })); document.querySelector("textarea")?.focus();');
  await settle();
  assert.equal(await evaluate('document.activeElement.tagName'), 'TEXTAREA', 'outside click preserves newly focused control');
  await evaluate('window.uiPreview.scenario("changes")');
  await settle();
  await evaluate('document.querySelector(".turn-head").click()');
  await settle();
  assert.equal(await evaluate('document.querySelector(".turn-head").getAttribute("aria-expanded")'), 'false', 'step group collapses');
  await evaluate('document.querySelector(".turn-head").click();');
  await settle();
  await evaluate('document.querySelector(".step-row-head").click()');
  await settle();
  assert.equal(await evaluate('document.querySelector(".step-detail").textContent.includes("Read 126 lines")'), true, 'step output remains available');
  await evaluate('document.querySelector(".step-row-head").click(); document.querySelector(".turn-changes-head").click();');
  await settle();
  await evaluate('document.querySelector(".turn-file-row").scrollIntoView({block: "nearest"}); document.querySelector(".turn-file-row").focus();');
  await settle();
  const fileBounds = await evaluate('(() => { const row = document.querySelector(".turn-file-row").getBoundingClientRect(); const stream = document.querySelector(".stream").getBoundingClientRect(); return { left: row.left, right: row.right, min: stream.left, max: stream.right }; })()');
  assert.ok(fileBounds.left >= fileBounds.min && fileBounds.right <= fileBounds.max, `long changed file stays in column: ${JSON.stringify(fileBounds)}`);
  await evaluate('document.querySelector(".turn-file-row").click()');
  await settle();
  assert.equal(await evaluate('window.uiPreview.events().some(event => event.type === "file" && event.value.endsWith("session-refresh.ts"))'), true, 'Enter opens changed file');
  await evaluate('document.querySelector(".turn-undo-btn").click()');
  await settle();
  assert.equal(await evaluate('window.uiPreview.events().some(event => event.type === "undo" && event.value === "tools")'), true, 'undo targets original turn');
  fs.writeFileSync(path.join(output, 'changed-files-keyboard.png'), (await window.webContents.capturePage()).toPNG());
  await evaluate('window.uiPreview.scenario("tool-failure")');
  await settle();
  assert.equal(await evaluate('document.querySelector(".turn-state-label").textContent'), '1 个步骤失败', 'failure is not presented as success');
  await evaluate('window.uiPreview.scenario("approval")');
  await settle();
  assert.equal(await evaluate('document.querySelector("[data-session-id=current] .rail-convo-state").textContent'), '待审批 1', 'approval has readable session status');
};
