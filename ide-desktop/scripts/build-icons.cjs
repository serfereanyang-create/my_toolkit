#!/usr/bin/env node
const sharp = require('sharp');
const fs = require('node:fs');
const path = require('node:path');

const outDir = path.join(__dirname, '..', 'resources');

// Prefer the committed raster source (icon-source.jpg) so a custom brand image
// survives every rebuild; fall back to the vector icon.svg when it is absent.
const rasterSource = path.join(outDir, 'icon-source.jpg');
const svgPath = path.join(outDir, 'icon.svg');

function loadSource() {
  if (fs.existsSync(rasterSource)) {
    console.log('Building icon assets from icon-source.jpg...');
    return fs.readFileSync(rasterSource);
  }
  console.log('Building icon assets from icon.svg...');
  return fs.readFileSync(svgPath);
}

async function buildIcons() {
  const sourceBuffer = loadSource();

  // PNG sizes for supported platforms.
  const sizes = [16, 32, 48, 64, 128, 256, 512, 1024];

  for (const size of sizes) {
    await sharp(sourceBuffer)
      .resize(size, size, { fit: 'cover', position: 'centre' })
      .png()
      .toFile(path.join(outDir, `icon-${size}.png`));
    console.log(`  built icon-${size}.png`);
  }

  // Windows ICO containing the standard shell sizes.
  const icoSizes = [16, 32, 48, 256];
  const icoBuffers = await Promise.all(
    icoSizes.map(size => sharp(sourceBuffer).resize(size, size, { fit: 'cover', position: 'centre' }).png().toBuffer())
  );
  
  // Simple ICO file builder (header + directory + PNGs)
  const icoHeader = Buffer.alloc(6);
  icoHeader.writeUInt16LE(0, 0); // Reserved
  icoHeader.writeUInt16LE(1, 2); // Type: ICO
  icoHeader.writeUInt16LE(icoSizes.length, 4);
  
  const directorySize = 16 * icoSizes.length;
  const directory = Buffer.alloc(directorySize);
  let offset = 6 + directorySize;
  
  icoBuffers.forEach((buf, i) => {
    const pos = i * 16;
    const size = icoSizes[i];
    directory.writeUInt8(size === 256 ? 0 : size, pos); // Width
    directory.writeUInt8(size === 256 ? 0 : size, pos + 1); // Height
    directory.writeUInt8(0, pos + 2); // Color palette
    directory.writeUInt8(0, pos + 3); // Reserved
    directory.writeUInt16LE(1, pos + 4); // Color planes
    directory.writeUInt16LE(32, pos + 6); // Bits per pixel
    directory.writeUInt32LE(buf.length, pos + 8); // Image size
    directory.writeUInt32LE(offset, pos + 12); // Image offset
    offset += buf.length;
  });
  
  const icoFile = Buffer.concat([icoHeader, directory, ...icoBuffers]);
  fs.writeFileSync(path.join(outDir, 'icon.ico'), icoFile);
  console.log('  built icon.ico (Windows)');

  // Second copy under a stable, app-specific name. Explorer caches shortcut
  // icons by path, so pointing .lnk files at this path keeps them immune to a
  // stale entry left behind by the generic `icon.ico` name.
  fs.writeFileSync(path.join(outDir, 'yoycode-app.ico'), icoFile);
  console.log('  built yoycode-app.ico (shortcut icon)');

  // macOS ICNS generation requires iconutil or a packaging tool.
  console.log('  macOS ICNS can be generated by iconutil or electron-builder');
  console.log('Icon build complete');
}

buildIcons().catch((error) => {
  console.error('Icon build failed:', error);
  process.exit(1);
});
